#!/bin/sh
# Writes ios/Flutter/Maps.xcconfig (gitignored) from env/maps.json so Info.plist
# can read $(MAPS_IOS_KEY). Empty when the file or key is missing.
set -eu
cd "$(dirname "$0")/.."
python3 - <<'PY'
import json, os
key = ""
if os.path.exists("env/maps.json"):
    key = json.load(open("env/maps.json")).get("MAPS_IOS_KEY", "")
with open("ios/Flutter/Maps.xcconfig", "w") as f:
    f.write("// Generated by tool/write_maps_xcconfig.sh. Contains a key: do not commit.\n")
    f.write(f"MAPS_IOS_KEY = {key}\n")
print("wrote ios/Flutter/Maps.xcconfig (key %s)" % ("set" if key else "EMPTY"))
PY
