#!/bin/sh
# Prepares ios/ for an Xcode Product > Archive.
#
# Xcode builds with whatever the last `flutter` command wrote into
# ios/Flutter/Generated.xcconfig: entry file, dart-defines, version. Another
# `flutter run` or integration test (other entry file, test defines, no
# Supabase keys) would otherwise end up in the archive. This script pins the
# Release configuration in ios/Flutter/ReleaseOverrides.xcconfig (gitignored,
# included by Release.xcconfig only) and then runs a release build to verify.
#
# Usage: tool/prepare_ios_archive.sh [env/supabase.json] [--skip-build]
set -eu
cd "$(dirname "$0")/.."
src="env/supabase.json"
build=1
for arg in "$@"; do
  case "$arg" in
    --skip-build) build=0 ;;
    *) src="$arg" ;;
  esac
done
out="ios/Flutter/ReleaseOverrides.xcconfig"
python3 - "$src" "$out" <<'PY'
import base64, json, re, sys
src, out = sys.argv[1], sys.argv[2]
values = json.load(open(src))
for key in ("SUPABASE_URL", "SUPABASE_ANON_KEY"):
    if not values.get(key):
        sys.exit(f"{src} is missing {key}")
version = re.search(r"^version:\s*(\S+)\+(\d+)\s*$", open("pubspec.yaml").read(), re.M)
if not version:
    sys.exit("pubspec.yaml version must look like 1.0.0+N")
name, number = version.groups()
encoded = ",".join(
    base64.b64encode(f"{k}={v}".encode()).decode() for k, v in values.items()
)
with open(out, "w") as f:
    f.write("// Generated by tool/prepare_ios_archive.sh. Contains keys: do not commit.\n")
    f.write("FLUTTER_TARGET = lib/main.dart\n")
    f.write(f"FLUTTER_BUILD_NAME = {name}\n")
    f.write(f"FLUTTER_BUILD_NUMBER = {number}\n")
    f.write(f"DART_DEFINES = {encoded}\n")
print(f"pinned Release: lib/main.dart, version {name}+{number}, defines {', '.join(values)}")
PY
if [ "$build" = 1 ]; then
  flutter build ios --release --no-codesign --dart-define-from-file="$src"
fi
